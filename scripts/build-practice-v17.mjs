import {readFileSync,writeFileSync} from 'node:fs';
import {stripTypeScriptTypes} from 'node:module';
const root='supabase/functions/simab-central-quests/';
function wrap(file,name,imports=''){
 let code=readFileSync(root+file,'utf8');
 const names=[...code.matchAll(/export (?:async )?(?:function|const|class) (\w+)/g)].map(m=>m[1]);
 code=stripTypeScriptTypes(code.replace(/^import .*$/gm,'')).replace(/\bexport /g,'');
 return `const ${name}=(()=>{${imports}\n${code}\nreturn {${names.join(',')}};})();\n`;
}
const out='/* Generated by scripts/build-practice-v17.mjs. FREE, offline, no wallet credits. */\n(()=>{\n'+wrap('games.ts','G')+wrap('table-games.ts','T','const {randomInt}=G;')+wrap('party-games.ts','P','const {randomInt,startHumanBG,moveHumanBG,legalBG}=G;const {startHumanH,moveHumanH,legalH,startL,moveHumanL,legalL,total}=T;')+`window.SimabPracticeRules={...P,total:T.total,randomInt:G.randomInt};})();\n`;
writeFileSync('assets/js/simab-practice-rules-v17.js',out);
